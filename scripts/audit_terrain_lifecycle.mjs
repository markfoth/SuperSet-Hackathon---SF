import { chromium, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage({reducedMotion:'reduce'});
await page.goto(process.env.CG_BASE_URL || 'http://localhost:5192');
const map = page.locator('.map');
await expect(map).toHaveAttribute('data-vector-loaded','true');
const snapshot = () => page.evaluate(() => { const m=document.querySelector('.map').__commonGroundMap; return {terrain:m.getTerrain(),sources:Object.keys(m.getStyle().sources),pitch:m.getPitch(),centre:m.getCenter().toArray()}; });
await page.getByRole('button',{name:'3D buildings',exact:true}).click();
await page.getByRole('button',{name:'Terrain',exact:true}).click();
await expect(map).toHaveAttribute('data-terrain','true');
const cycles=[];
for(let i=0;i<5;i++) {
 await page.getByRole('button',{name:'Terrain',exact:true}).click();
 await expect(map).toHaveAttribute('data-terrain','false');
 await expect(map).toHaveAttribute('data-3d','true');
 await page.getByRole('button',{name:'Terrain',exact:true}).click();
 await expect(map).toHaveAttribute('data-terrain','true');
 cycles.push(await snapshot());
}
await page.evaluate(() => {const m=document.querySelector('.map').__commonGroundMap;m.setStyle(m.getStyle());});
await expect(map).toHaveAttribute('data-terrain','true');
await page.waitForTimeout(1500);
const afterStyle=await snapshot();
if(!afterStyle.terrain) throw Error('Terrain lost after style reset');
await page.getByRole('button',{name:'3D buildings',exact:true}).click();
await expect(map).toHaveAttribute('data-3d','false');
await expect(map).toHaveAttribute('data-terrain','true');
await page.getByRole('button',{name:'Map tilt',exact:true}).click();
await expect(map).toHaveAttribute('data-pitch','0');
await expect(map).toHaveAttribute('data-terrain','true');
const client=await page.context().newCDPSession(page);
await client.send('HeapProfiler.collectGarbage');
const heap=await client.send('Runtime.getHeapUsage');
await writeFile('docs/audit/terrain-lifecycle.json',JSON.stringify({cycles,afterStyle,final:await snapshot(),heap},null,2));
await browser.close();
console.log('Passed five terrain cycles, buildings independence, tilt independence and style restoration.');
