#!/usr/bin/env python
"""Canonical H3-9 matching geography. Reuses the existing neighbourhood sample grid.

Run after process_datasets.py; public/data is still generated by predev/prebuild.
"""
from __future__ import annotations

import json
from pathlib import Path

import geopandas as gpd
import h3
from shapely.geometry import Point

from _common import METRIC_CRS, PROCESSED_DIR, rel, today, update_manifest
from process_datasets import hex_polygon, load_nhoods, sample_points, write_geojson


def canonical_grid() -> gpd.GeoDataFrame:
    """Unique stable H3 ids; include coastal/border cells, clipped to the study land.

    A parent is assigned by greatest land overlap, never by duplicating a cell.
    The true H3 centre is retained even if it lies outside a coastal clipped polygon;
    a representative land point is used for access/commute checks in that case.
    """
    nh = load_nhoods().to_crs(METRIC_CRS)
    land = nh.geometry.union_all()
    seeds = set(sample_points()["h3"])
    cells = sorted({c for seed in seeds for c in h3.grid_disk(seed, 1)})
    grid = gpd.GeoDataFrame({"h3": cells}, geometry=[hex_polygon(c) for c in cells], crs=4326).to_crs(METRIC_CRS)
    grid["geometry"] = grid.geometry.intersection(land)
    grid = grid[grid.area >= 1000].copy()  # drop <0.001 km² coastal slivers, never whole inland cells
    overlaps = gpd.overlay(grid, nh[["id", "geometry"]], how="intersection", keep_geom_type=True)
    overlaps["overlap_m2"] = overlaps.area
    parents = overlaps.sort_values(["h3", "overlap_m2", "id"]).drop_duplicates("h3", keep="last").set_index("h3")["id"]
    grid["nhood_id"] = grid["h3"].map(parents)
    grid["area_m2"] = grid.area.round().astype(int)
    grid["land_share"] = (grid.area / grid["h3"].map(lambda c: h3.cell_area(c, unit="m^2"))).round(3)
    points = []
    for cell, geom in zip(grid["h3"], grid.geometry):
        lat, lon = h3.cell_to_latlng(cell)
        centre = gpd.GeoSeries([Point(lon, lat)], crs=4326).to_crs(METRIC_CRS).iloc[0]
        points.append(centre if geom.covers(centre) else geom.representative_point())
    checks = gpd.GeoSeries(points, crs=METRIC_CRS).to_crs(4326)
    grid["center_lat"] = grid["h3"].map(lambda c: round(h3.cell_to_latlng(c)[0], 6))
    grid["center_lon"] = grid["h3"].map(lambda c: round(h3.cell_to_latlng(c)[1], 6))
    grid["check_lat"] = checks.y.to_numpy().round(6)
    grid["check_lon"] = checks.x.to_numpy().round(6)
    grid["residential"] = None
    grid["residential_reason"] = "Land use unverified; no parcel inventory"
    return grid.reset_index(drop=True)


def build() -> dict:
    grid = canonical_grid()
    path, count = write_geojson(grid, "area_cells.geojson", meta={
        "generated": today(), "h3_resolution": 9,
        "parent_method": "largest overlap with one of 41 neighbourhood polygons",
        "geometry": "H3 polygons clipped to SF neighbourhood land; <1000 m² coastal slivers omitted",
        "matching_point": "H3 centre, or representative land point for coastal clipped cells",
        "null": "measurement unavailable, never a zero, pass or failure",
    })
    update_manifest("area_cells", {
        "source": "Derived from H3 and DataSF Analysis Neighborhoods; contextual inputs recorded separately",
        "source_url": "https://data.sf.gov/d/j2bu-swwd", "licence": "Inherits inputs; H3 Apache-2.0",
        "downloaded_at": today(), "measurement_period": "Per input dataset",
        "resolution": "H3 resolution 9 (~0.105 km²); coarser indicators retain original source ids",
        "feature_count": count, "raw_path": "See individual source entries",
        "processed_path": [rel(path)], "script": "scripts/build_area_cells.py",
        "refresh": "after rebuilding any input", "status": "processed",
        "limitations": "Centre-based access and commute checks describe a representative location, not every address. "
                        "Parent assignment is approximate along neighbourhood borders. Land use is incomplete.",
    })
    return {"cells": count}


if __name__ == "__main__":
    print(build())
